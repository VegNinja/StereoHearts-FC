-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.club_records (
    id bigint generated by default as identity primary key,
    club_id text not null,
    club_name text not null,
    record_type text not null,
    record_key text not null,
    payload jsonb not null,
    captured_at timestamptz not null default now(),
    constraint club_records_unique unique (club_id, record_type, record_key)
);

create index if not exists club_records_club_type_idx
    on public.club_records (club_id, record_type);
create index if not exists club_records_captured_idx
    on public.club_records (captured_at desc);

-- This starter uses the Supabase service-role key server-side only.
-- Do not expose that key in browser code or commit it to GitHub.
alter table public.club_records enable row level security;
